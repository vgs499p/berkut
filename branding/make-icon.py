#!/usr/bin/env python3
"""Draws the Berkut icon: a Su-47 seen from above, flying toward the top-right
corner, traced from a nose-left plan view (reference coordinates, x along the
aircraft from the nose, y across it with the centreline at 228). Writes
icon.svg, icon-dark.svg and icon-tinted.svg; render them with rsvg-convert."""
import math

K, CX, NOSE = 1.33, 228, 50          # reference px -> icon px, centreline, nose x

def pt(x, y):                         # reference (nose left) -> icon (nose up)
    return f"{512 + (y - CX) * K:.1f} {130 + (x - NOSE) * K:.1f}"

def path(points):
    return "M" + " L".join(pt(x, y) for x, y in points) + " Z"

def star(x, y, R, r):
    cx, cy = [float(v) for v in pt(x, y).split()]
    pts = []
    for i in range(10):
        a = math.radians(-90 + 36 * i); d = (R if i % 2 == 0 else r) * K
        pts.append(f"{cx + d * math.cos(a):.1f} {cy + d * math.sin(a):.1f}")
    return "M" + " L".join(pts) + " Z"

FUSELAGE = [(50, 228), (80, 233), (115, 240), (160, 244), (210, 247),
            (240, 256), (270, 272), (295, 287), (380, 292), (500, 295),
            (600, 298), (640, 299), (656, 292), (640, 284), (618, 280),
            (618, 262), (642, 258), (642, 228)]
NOZZLE = [(618, 228), (618, 238), (648, 240), (648, 256), (618, 258), (618, 228)]
RADOME = [(50, 228), (80, 233), (115, 240), (115, 228)]
CANARD = [(286, 288), (336, 330), (362, 330), (374, 290)]
WING = [(418, 293), (372, 440), (386, 450), (436, 450), (534, 300)]
TAILPLANE = [(518, 300), (626, 336), (646, 332), (646, 300)]

def mirrored(points):
    """The whole outline from its right half, without a seam on the centreline."""
    side = [p for p in points if p[1] != CX]
    rear = [points[-1]] if points[-1][1] == CX and points[-1] != points[0] else []
    return [points[0]] + side + rear + [(x, 2 * CX - y) for x, y in reversed(side)]

def svg(sky, body, panel, edge, radome, glass, star_red, star_white):
    half = "\n".join([
        f'      <path d="{path(WING)}" fill="{body}"/>',
        f'      <path d="{path(CANARD)}" fill="{body}"/>',
        f'      <path d="{path(TAILPLANE)}" fill="{body}"/>',
        f'      <path d="{star(412, 392, 24, 9.5)}" fill="{star_white}" stroke="none"/>',
        f'      <path d="{star(412, 392, 18, 7)}" fill="{star_red}" stroke="none"/>',
    ])
    top, mid, bottom = sky
    return f'''<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" viewBox="0 0 1024 1024">
  <!-- Generated by make-icon.py: a Su-47 Berkut seen from above. -->
  <defs>
    <linearGradient id="bg" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="{top}"/>
      <stop offset="0.6" stop-color="{mid}"/>
      <stop offset="1" stop-color="{bottom}"/>
    </linearGradient>
    <linearGradient id="glass" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="{glass[0]}"/>
      <stop offset="1" stop-color="{glass[1]}"/>
    </linearGradient>
    <g id="half" stroke="{edge}" stroke-width="3" stroke-linejoin="round">
{half}
    </g>
  </defs>
  <rect width="1024" height="1024" fill="url(#bg)"/>
  <g transform="translate(0 -6) rotate(45 512 530)">
    <use xlink:href="#half"/>
    <use xlink:href="#half" transform="translate(1024 0) scale(-1 1)"/>
    <path d="{path(mirrored(FUSELAGE))}" fill="{body}" stroke="{edge}" stroke-width="3" stroke-linejoin="round"/>
    <path d="{path(mirrored(NOZZLE))}" fill="{panel}" stroke="{edge}" stroke-width="3"/>
    <path d="{path(mirrored(RADOME))}" fill="{radome}" stroke="{edge}" stroke-width="3" stroke-linejoin="round"/>
    <line x1="512" y1="{130 - 45 * K:.1f}" x2="512" y2="130" stroke="{edge}" stroke-width="5" stroke-linecap="round"/>
    <path d="M{pt(145, 228)} C {pt(150, 240)}, {pt(220, 240)}, {pt(228, 228)} C {pt(220, 216)}, {pt(150, 216)}, {pt(145, 228)} Z" fill="url(#glass)" stroke="{edge}" stroke-width="3"/>
    <line x1="{pt(178, 216).split()[0]}" y1="{pt(178, 216).split()[1]}" x2="{pt(178, 240).split()[0]}" y2="{pt(178, 240).split()[1]}" stroke="{edge}" stroke-width="5"/>
  </g>
</svg>
'''

open("icon.svg", "w").write(svg(("#A9CFF0", "#6C9FD0", "#3A6EA6"),
    "#2A2E33", "#6B737C", "#4B535C", "#ECEEF0", ("#9CC8EE", "#1E3A57"), "#D7262E", "#FFFFFF"))
open("icon-dark.svg", "w").write(svg(("#22344A", "#141F2C", "#070B10"),
    "#3A4048", "#7A838D", "#5E6873", "#ECEEF0", ("#9CC8EE", "#1E3A57"), "#E0333A", "#FFFFFF"))
open("icon-tinted.svg", "w").write(svg(("#000000", "#000000", "#000000"),
    "#C8C8C8", "#8A8A8A", "#9A9A9A", "#FFFFFF", ("#707070", "#404040"), "#5A5A5A", "#FFFFFF"))
